#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=CATALOG_DB_PASSWORD="$CATALOG_DB_PASSWORD" \
  --set=USERS_DB_PASSWORD="$USERS_DB_PASSWORD" \
  --set=CIRCULATION_DB_PASSWORD="$CIRCULATION_DB_PASSWORD" <<'SQL'
CREATE ROLE catalogo_user LOGIN PASSWORD :'CATALOG_DB_PASSWORD';
CREATE ROLE usuarios_user LOGIN PASSWORD :'USERS_DB_PASSWORD';
CREATE ROLE circulacao_user LOGIN PASSWORD :'CIRCULATION_DB_PASSWORD';
CREATE DATABASE inko_catalogo OWNER catalogo_user;
CREATE DATABASE inko_usuarios OWNER usuarios_user;
CREATE DATABASE inko_circulacao OWNER circulacao_user;
SQL
